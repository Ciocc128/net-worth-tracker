describe('snapshotRequestSchema', () => {
  it('accepts a minimal valid body', () => {
    expect(
      snapshotRequestSchema.safeParse({ userId: 'user-1' }).success
    ).toBe(true);
  });

  // C7: the secret no longer travels in the body.
  it('rejects a cronSecret (strict)', () => {
    expect(
      snapshotRequestSchema.safeParse({ userId: 'user-1', cronSecret: 'secret' }).success
    ).toBe(false);
  });

  // RI6 (doc/snapshot-integri/README.md § 5.3): the target is always the current month; a caller
  // naming one is refused, never silently given another.
  it.each([
    ['a year', { year: 2025 }],
    ['a month', { month: 6 }],
    ['any other key', { fenicottero: true }],
  ])('rejects %s (strict)', (_label, extra) => {
    expect(snapshotRequestSchema.safeParse({ userId: 'user-1', ...extra }).success).toBe(false);
  });

  it('rejects empty userId', () => {
    expect(snapshotRequestSchema.safeParse({ userId: '' }).success).toBe(false);
  });

  it.each([
    ['year too low', { userId: 'u', year: 1999 }],
    ['year too high', { userId: 'u', year: 2101 }],
    ['month 0', { userId: 'u', month: 0 }],
    ['month 13', { userId: 'u', month: 13 }],
    ['fractional month', { userId: 'u', month: 1.5 }],
  ])('rejects %s', (_, body) => {
    expect(snapshotRequestSchema.safeParse(body).success).toBe(false);
  });
});

describe('dividendDataSchema', () => {
  const basePayload = {
    assetId: 'asset-1',
    exDate: '2024-06-15T00:00:00.000Z',
    paymentDate: '2024-06-20T00:00:00.000Z',
    dividendPerShare: 0.5,
    quantity: 100,
    grossAmount: 50,
    taxAmount: 13,
    netAmount: 37,
    currency: 'EUR',
    dividendType: 'ordinary',
    isAutoGenerated: false,
  };

  it('accepts a valid dividend payload', () => {
    expect(dividendDataSchema.safeParse(basePayload).success).toBe(true);
  });

  it('coerces ISO date strings to Date objects', () => {
    const result = dividendDataSchema.safeParse(basePayload);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.exDate).toBeInstanceOf(Date);
      expect(result.data.paymentDate).toBeInstanceOf(Date);
    }
  });

  it('rejects empty assetId', () => {
    expect(dividendDataSchema.safeParse({ ...basePayload, assetId: '' }).success).toBe(false);
  });

  it.each([
    ['grossAmount', Infinity],
    ['taxAmount', NaN],
    ['netAmount', Infinity],
    ['dividendPerShare', Infinity],
  ])('rejects non-finite %s', (field, value) => {
    expect(dividendDataSchema.safeParse({ ...basePayload, [field]: value }).success).toBe(false);
  });

  it('rejects unknown dividendType', () => {
    expect(
      dividendDataSchema.safeParse({ ...basePayload, dividendType: 'special' }).success
    ).toBe(false);
  });

  it('accepts all valid dividendType values', () => {
    const types = ['ordinary', 'extraordinary', 'interim', 'final', 'coupon', 'finalPremium'];
    for (const t of types) {
      expect(
        dividendDataSchema.safeParse({ ...basePayload, dividendType: t }).success
      ).toBe(true);
    }
  });

  it('validates assetIsin when provided', () => {
    expect(
      dividendDataSchema.safeParse({ ...basePayload, assetIsin: 'IT0005672024' }).success
    ).toBe(true);
    expect(
      dividendDataSchema.safeParse({ ...basePayload, assetIsin: 'INVALID' }).success
    ).toBe(false);
  });

  it('accepts payload without optional assetIsin', () => {
    expect(dividendDataSchema.safeParse(basePayload).success).toBe(true);
  });

  // A Date the client could not build serializes as null; coerced alone it became 1970-01-01.
  it.each([
    ['exDate', null],
    ['paymentDate', null],
    ['exDate', 1718409600000],
    ['paymentDate', ''],
  ])('rejects a %s of %s instead of coercing it', (field, value) => {
    expect(dividendDataSchema.safeParse({ ...basePayload, [field]: value }).success).toBe(false);
  });

  it('rejects a null date on a partial update too', () => {
    expect(dividendDataSchema.partial().safeParse({ exDate: null }).success).toBe(false);
  });
});

describe('assetTransactionDataSchema / assetTransactionUpdateSchema', () => {
  const basePayload = {
    assetId: 'asset-1',
    type: 'buy',
    date: '2024-06-15T00:00:00.000Z',
    quantity: 10,
    pricePerUnit: 100,
  };

  it('accepts an ISO date string and returns a Date', () => {
    const result = assetTransactionDataSchema.safeParse(basePayload);
    expect(result.success).toBe(true);
    if (result.success) expect(result.data.date).toBeInstanceOf(Date);
  });

  it.each([null, 1718409600000, ''])('rejects a date of %s instead of coercing it', (value) => {
    expect(assetTransactionDataSchema.safeParse({ ...basePayload, date: value }).success).toBe(false);
  });

  it('rejects a null date on an update, and accepts an update without one', () => {
    expect(assetTransactionUpdateSchema.safeParse({ date: null }).success).toBe(false);
    expect(assetTransactionUpdateSchema.safeParse({ quantity: 5 }).success).toBe(true);
  });
});

describe('parseOr400', () => {
  it('returns ok:true with typed data for valid input', () => {
    const result = parseOr400(isinSchema, 'IT0005672024');
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.data).toBe('IT0005672024');
    }
  });

  it('returns ok:false with a NextResponse 400 for invalid input', async () => {
    const result = parseOr400(isinSchema, 'INVALID');
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.response.status).toBe(400);
      const body = await result.response.json();
      expect(body).toHaveProperty('error');
      expect(body).toHaveProperty('details');
    }
  });

  it('includes flattened field errors in the 400 response', async () => {
    const result = parseOr400(snapshotRequestSchema, { month: 13 });
    expect(result.ok).toBe(false);
    if (!result.ok) {
      const body = await result.response.json();
      // userId is missing, month is out of range — both should appear in fieldErrors
      expect(body.details.fieldErrors).toBeDefined();
    }
  });
});

// AV1 — doc/snapshot-integri/README.md § 5.9: each schema takes a valid body, refuses a wrong type
// and an unknown key.
describe('AV1 — the strict schemas of A5', () => {
  const validManual = {
    userId: 'u', year: 2026, month: 10, totalNetWorth: 10000, liquidNetWorth: 7000, illiquidNetWorth: 3000,
    byAssetClass: { equity: 6000, bonds: 4000 }, byAsset: [{ assetId: 'a', ticker: 'FENI', name: 'Fenicottero', quantity: 1, price: 10000, totalValue: 10000 }],
  };
  const cases: Array<[string, { safeParse: (v: unknown) => { success: boolean } }, Record<string, unknown>, Record<string, unknown>]> = [
    ['manual snapshot', manualSnapshotSchema, validManual, { totalNetWorth: 'abc' }],
    ['restore', snapshotRestoreSchema, { userId: 'u', year: 2026, month: 10 }, { month: 1.5 }],
    ['hall-of-fame/recalculate', hallOfFameRecalculateSchema, { userId: 'u' }, { userId: 42 }],
    ['prices/update', pricesUpdateSchema, { userId: 'u' }, { userId: null }],
    ['assets/[assetId] DELETE', assetDeleteSchema, { userId: 'u' }, { userId: [] }],
    ['memory PATCH', assistantMemoryPatchSchema, { userId: 'u', item: { id: 'i', text: 'Ornitorinco', category: 'goal', status: 'active' } }, { action: 'deleteEverything' }],
    ['memory DELETE', assistantMemoryDeleteSchema, { userId: 'u', itemId: 'i' }, { resetAll: 'yes' }],
    ['stream', assistantStreamRequestSchema, { userId: 'u', mode: 'chat', prompt: 'Ciao', chatContext: 'month', month: { year: 2026, month: 3 } }, { mode: 'fenicottero' }],
  ];

  it.each(cases)('%s: valid, wrong type, unknown key', (_label, schema, valid, wrong) => {
    expect(schema.safeParse(valid).success).toBe(true);
    expect(schema.safeParse({ ...valid, ...wrong }).success).toBe(false);
    expect(schema.safeParse({ ...valid, fenicottero: true }).success).toBe(false);
  });

  it('the manual snapshot refuses the percentages it used to receive, an unknown class, 501 rows', () => {
    expect(manualSnapshotSchema.safeParse({ ...validManual, assetAllocation: { equity: 60 } }).success).toBe(false);
    expect(manualSnapshotSchema.safeParse({ ...validManual, byAssetClass: { fenicottero: 10000 } }).success).toBe(false);
    const row = validManual.byAsset[0];
    expect(manualSnapshotSchema.safeParse({ ...validManual, byAsset: Array.from({ length: 501 }, () => row) }).success).toBe(false);
    // A net worth below zero is legal (loans).
    expect(manualSnapshotSchema.safeParse({ ...validManual, totalNetWorth: -500, liquidNetWorth: -500, illiquidNetWorth: 0, byAssetClass: { cash: -500 } }).success).toBe(true);
  });

  it('the stream prompt: 8.000 characters pass, 8.001 and a blank one do not', () => {
    const body = { userId: 'u', mode: 'chat' };
    expect(assistantStreamRequestSchema.safeParse({ ...body, prompt: 'a'.repeat(8000) }).success).toBe(true);
    expect(assistantStreamRequestSchema.safeParse({ ...body, prompt: 'a'.repeat(8001) }).success).toBe(false);
    expect(assistantStreamRequestSchema.safeParse({ ...body, prompt: '   ' }).success).toBe(false);
  });

  it('a memory item cannot carry fields the panel never sends', () => {
    expect(assistantMemoryPatchSchema.safeParse({ userId: 'u', item: { id: 'i', text: 'x', category: 'goal', userId: 'stranger' } }).success).toBe(false);
  });

  it('the asset id of a path', () => {
    expect(assetIdParamSchema.safeParse('asset-1').success).toBe(true);
    expect(assetIdParamSchema.safeParse('').success).toBe(false);
    expect(assetIdParamSchema.safeParse('a/b').success).toBe(false);
    expect(assetIdParamSchema.safeParse('x'.repeat(201)).success).toBe(false);
  });
});
