/**
 * PUT /api/dividends/[dividendId] — RQ10 of doc/dividendi-quantita: a hand correction of an
 * app-generated payment's quantity or amounts marks it, so the ledger hook and the cron leave it
 * alone. Real route and service over the in-memory Admin fake. Figures invented (WORKFLOW § 1.7).
 */

import { beforeEach, describe, expect, it, vi } from 'vitest';
import { NextRequest } from 'next/server';
import { Timestamp } from 'firebase-admin/firestore';

vi.mock('server-only', () => ({}));
vi.mock('@/lib/firebase/config', () => ({ auth: { currentUser: null }, db: {} }));
vi.mock('@/lib/firebase/admin', async () => (await import('./helpers/adminFake')).adminModule);
vi.mock('@/lib/services/currencyConversionService', () => ({
  convertMultipleToEur: vi.fn(),
  getExchangeRateToEur: vi.fn(),
}));

import { fake, bearer } from './helpers/adminFake';
import { PUT } from '@/app/api/dividends/[dividendId]/route';

const DATE = Timestamp.fromDate(new Date('2026-12-10T12:00:00Z'));
const params = (dividendId: string) => ({ params: Promise.resolve({ dividendId }) });

function put(id: string, updates: Record<string, unknown>) {
  return PUT(
    new NextRequest(`http://localhost/api/dividends/${id}`, {
      method: 'PUT',
      headers: { 'content-type': 'application/json', ...bearer('owner-1') },
      body: JSON.stringify({ updates }),
    }),
    params(id),
  );
}

beforeEach(() => {
  fake.reset();
  fake.allow('owner-1');
  const row = {
    userId: 'owner-1', assetId: 'asset-1', assetTicker: 'FENI', assetName: 'Fenicottero',
    exDate: DATE, paymentDate: DATE, quantity: 100, dividendPerShare: 1, grossAmount: 100, taxAmount: 26,
    netAmount: 74, currency: 'EUR', dividendType: 'coupon',
  };
  fake.set('dividends/auto', { ...row, isAutoGenerated: true });
  fake.set('dividends/manual', { ...row, isAutoGenerated: false });
});

describe('RQ10 — the correction by hand wins', () => {
  it('marks an app-generated payment whose amounts are edited', async () => {
    const response = await put('auto', { grossAmount: 120, netAmount: 88.8, taxAmount: 31.2 });
    expect(response.status).toBe(200);
    expect(fake.get('dividends/auto')?.manuallyEdited).toBe(true);
    expect(fake.get('dividends/auto')?.grossAmount).toBe(120);
  });

  it('marks it when only the quantity is edited', async () => {
    await put('auto', { quantity: 80 });
    expect(fake.get('dividends/auto')?.manuallyEdited).toBe(true);
  });

  it('does not mark it when only the notes change', async () => {
    await put('auto', { notes: 'Ornitorinco' });
    expect(fake.get('dividends/auto')?.manuallyEdited).toBeUndefined();
  });

  it('never marks a payment the owner typed in', async () => {
    await put('manual', { grossAmount: 120 });
    expect(fake.get('dividends/manual')?.manuallyEdited).toBeUndefined();
  });

  it('the client cannot set the mark itself', async () => {
    await put('auto', { notes: 'x', manuallyEdited: true });
    expect(fake.get('dividends/auto')?.manuallyEdited).toBeUndefined();
  });
});
