import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

vi.mock('server-only', () => ({}));
vi.mock('@/lib/firebase/config', () => ({ auth: { currentUser: null }, db: {} }));

const { assetGetMock, getTransactionsMock, getDividendsByAssetMock, createDividendMock, updateDividendMock, deleteDividendMock } =
  vi.hoisted(() => ({
    assetGetMock: vi.fn(),
    getTransactionsMock: vi.fn(),
    getDividendsByAssetMock: vi.fn(),
    createDividendMock: vi.fn(),
    updateDividendMock: vi.fn(),
    deleteDividendMock: vi.fn(),
  }));

vi.mock('@/lib/firebase/admin', () => ({
  adminDb: { collection: vi.fn(() => ({ doc: vi.fn(() => ({ get: assetGetMock })) })) },
}));
vi.mock('@/lib/server/assetAdminRepository', () => ({
  getAssetTransactionsForAssetAdmin: getTransactionsMock,
}));
vi.mock('@/lib/services/dividendService', () => ({
  getDividendsByAsset: getDividendsByAssetMock,
  createDividend: createDividendMock,
  updateDividend: updateDividendMock,
  deleteDividend: deleteDividendMock,
}));

import { syncOpenPaymentsForAsset } from '@/lib/server/dividendLedgerSync';
import type { Dividend } from '@/types/dividend';

// Every date at noon: a midnight fixture would hide timezone bugs.
const d = (y: number, m: number, day: number) => new Date(y, m - 1, day, 12);
const NOW = d(2026, 11, 15);

function buy(date: Date, quantity: number, id: string) {
  return {
    id,
    userId: 'u1',
    assetId: 'a1',
    type: 'buy',
    date,
    quantity,
    pricePerUnit: 1,
    priceEur: 1,
    createdAt: date,
    updatedAt: date,
  };
}

function setAsset(quantity: number, extra: Record<string, unknown> = {}) {
  assetGetMock.mockResolvedValue({
    exists: true,
    id: 'a1',
    data: () => ({
      userId: 'u1',
      ticker: 'BTP',
      name: 'BTP 2032',
      currency: 'EUR',
      quantity,
      taxRate: 12.5,
      averageCost: 1,
      bondDetails: {
        couponRate: 2,
        couponFrequency: 'semiannual',
        issueDate: d(2024, 1, 15),
        maturityDate: d(2032, 1, 15),
        nominalValue: 1,
      },
      ...extra,
    }),
  });
}

function coupon(extra: Partial<Dividend> = {}): Dividend {
  return {
    id: 'c1',
    userId: 'u1',
    assetId: 'a1',
    assetTicker: 'BTP',
    assetName: 'BTP 2032',
    exDate: d(2027, 1, 15),
    paymentDate: d(2027, 1, 15),
    dividendPerShare: 0.01,
    quantity: 5000,
    grossAmount: 50,
    taxAmount: 6.25,
    netAmount: 43.75,
    currency: 'EUR',
    dividendType: 'coupon',
    isAutoGenerated: true,
    createdAt: d(2026, 1, 1),
    updatedAt: d(2026, 1, 1),
    ...extra,
  } as Dividend;
}

describe('syncOpenPaymentsForAsset (RQ7)', () => {
  beforeEach(() => {
    vi.useFakeTimers();
    vi.setSystemTime(NOW);
    vi.clearAllMocks();
  });
  afterEach(() => vi.useRealTimers());

  it('CQ1: a purchase before the payment doubles the open coupon', async () => {
    setAsset(10000);
    getTransactionsMock.mockResolvedValue([buy(d(2025, 1, 10), 5000, 't1'), buy(d(2026, 11, 10), 5000, 't2')]);
    getDividendsByAssetMock.mockResolvedValue([coupon()]);

    const result = await syncOpenPaymentsForAsset('u1', 'a1', NOW);

    expect(result.updated).toBe(1);
    const updates = updateDividendMock.mock.calls[0][1];
    expect(updateDividendMock.mock.calls[0][0]).toBe('c1');
    expect(updates.quantity).toBe(10000);
    expect(updates.grossAmount).toBeCloseTo(100, 10);
    expect(updates.taxAmount).toBeCloseTo(12.5, 10);
    expect(updates.netAmount).toBeCloseTo(87.5, 10);
    expect('expenseId' in updates).toBe(false); // never the unlink sentinel
  });

  it('CQ2: a partial sale lowers it', async () => {
    setAsset(2000);
    getTransactionsMock.mockResolvedValue([
      buy(d(2025, 1, 10), 5000, 't1'),
      { ...buy(d(2026, 11, 10), 3000, 't2'), type: 'sell' },
    ]);
    getDividendsByAssetMock.mockResolvedValue([coupon()]);

    await syncOpenPaymentsForAsset('u1', 'a1', NOW);

    const updates = updateDividendMock.mock.calls[0][1];
    expect(updates.quantity).toBe(2000);
    expect(updates.grossAmount).toBeCloseTo(20, 10);
    expect(updates.netAmount).toBeCloseTo(17.5, 10);
  });

  it('CQ3: selling everything removes the open coupon and the final premium, creates nothing', async () => {
    setAsset(0, { bondDetails: { ...bond(), finalPremiumRate: 0.8 } });
    getTransactionsMock.mockResolvedValue([buy(d(2025, 1, 10), 5000, 't1'), { ...buy(d(2026, 11, 10), 5000, 't2'), type: 'sell' }]);
    getDividendsByAssetMock.mockResolvedValue([
      coupon(),
      coupon({ id: 'p1', dividendType: 'finalPremium', exDate: d(2032, 1, 15), paymentDate: d(2032, 1, 15) }),
    ]);

    const result = await syncOpenPaymentsForAsset('u1', 'a1', NOW);

    expect(result.deleted).toBe(2);
    expect(deleteDividendMock.mock.calls.map((c) => c[0]).sort()).toEqual(['c1', 'p1']);
    expect(createDividendMock).not.toHaveBeenCalled();
  });

  it('CQ4: buying again after a total sale creates the next coupon on the new units', async () => {
    setAsset(4000);
    getTransactionsMock.mockResolvedValue([
      buy(d(2025, 1, 10), 5000, 't1'),
      { ...buy(d(2026, 10, 10), 5000, 't2'), type: 'sell' },
      buy(d(2026, 11, 14), 4000, 't3'),
    ]);
    getDividendsByAssetMock.mockResolvedValue([]);

    const result = await syncOpenPaymentsForAsset('u1', 'a1', NOW);

    expect(result.created).toBe(1);
    const data = createDividendMock.mock.calls[0][1];
    expect(data.dividendType).toBe('coupon');
    expect(data.quantity).toBe(4000);
    expect(data.grossAmount).toBeCloseTo(40, 10);
    expect(data.netAmount).toBeCloseTo(35, 10);
    expect(createDividendMock.mock.calls[0][5]).toBe(true);
  });

  it('CQ5: a hand-corrected coupon stays, a paid one is not an open payment', async () => {
    setAsset(10000);
    getTransactionsMock.mockResolvedValue([buy(d(2025, 1, 10), 5000, 't1'), buy(d(2026, 11, 10), 5000, 't2')]);
    getDividendsByAssetMock.mockResolvedValue([
      coupon({ manuallyEdited: true, grossAmount: 60 }),
      coupon({ id: 'c0', exDate: d(2026, 7, 15), paymentDate: d(2026, 7, 15), expenseId: 'e0' }),
    ]);

    const result = await syncOpenPaymentsForAsset('u1', 'a1', NOW);

    expect(updateDividendMock).not.toHaveBeenCalled();
    expect(deleteDividendMock).not.toHaveBeenCalled();
    expect(result).toEqual({ updated: 0, deleted: 0, created: 0 });
  });

  it('an asset of another account is not touched', async () => {
    setAsset(10000, { userId: 'someone-else' });
    const result = await syncOpenPaymentsForAsset('u1', 'a1', NOW);
    expect(result).toEqual({ updated: 0, deleted: 0, created: 0 });
    expect(getDividendsByAssetMock).not.toHaveBeenCalled();
  });
});

function bond() {
  return {
    couponRate: 2,
    couponFrequency: 'semiannual',
    issueDate: d(2024, 1, 15),
    maturityDate: d(2032, 1, 15),
    nominalValue: 1,
  };
}
