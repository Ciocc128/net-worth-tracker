/**
 * POST /api/dividends/scrape — D1, D6 and RQ12–RQ13 of doc/dividendi-quantita: the quantity
 * entitled at the ex-date, the instrument's rate, and the closed payments that do not match the
 * ledger, listed and never rewritten. Real route over the in-memory Admin fake.
 * Figures invented (WORKFLOW § 1.7); every date at noon.
 */

import { beforeEach, describe, expect, it, vi } from 'vitest';
import { NextRequest } from 'next/server';
import { Timestamp } from 'firebase-admin/firestore';

vi.mock('server-only', () => ({}));
vi.mock('@/lib/firebase/config', () => ({ auth: { currentUser: null }, db: {} }));
vi.mock('@/lib/firebase/admin', async () => (await import('./helpers/adminFake')).adminModule);
vi.mock('@/lib/services/currencyConversionService', () => ({
  convertMultipleToEur: vi.fn(),
  getExchangeRateToEur: vi.fn(),
}));

const { scrapeMock } = vi.hoisted(() => ({ scrapeMock: vi.fn() }));
vi.mock('@/lib/services/borsaItalianaScraperService', () => ({ scrapeDividendsByIsin: scrapeMock }));

import { fake, bearer } from './helpers/adminFake';
import { POST } from '@/app/api/dividends/scrape/route';

const at = (y: number, m: number, d: number) => new Date(y, m - 1, d, 12);
const ts = (date: Date) => Timestamp.fromDate(date);

function seedBuy(id: string, date: Date, quantity: number) {
  fake.set(`assetTransactions/${id}`, {
    userId: 'owner-1', assetId: 'asset-1', type: 'buy', date: ts(date), quantity,
    pricePerUnit: 10, priceEur: 10, createdAt: ts(date), updatedAt: ts(date),
  });
}

function scrape() {
  return POST(
    new NextRequest('http://localhost/api/dividends/scrape', {
      method: 'POST',
      headers: { 'content-type': 'application/json', ...bearer('owner-1') },
      body: JSON.stringify({ userId: 'owner-1', assetId: 'asset-1' }),
    }),
  );
}

beforeEach(() => {
  fake.reset();
  fake.allow('owner-1');
  vi.clearAllMocks();
  fake.set('assets/asset-1', {
    userId: 'owner-1', ticker: 'FENI', name: 'Fenicottero', isin: 'IT0000000001', type: 'stock',
    assetClass: 'equity', currency: 'EUR', quantity: 200, averageCost: 10, taxRate: 26,
    createdAt: ts(at(2020, 1, 1)),
  });
});

describe('POST /api/dividends/scrape', () => {
  it('DQ1: the ex-date of 2025 gets 100 units, not today’s 200', async () => {
    seedBuy('t1', at(2024, 3, 1), 100);
    seedBuy('t2', at(2026, 10, 5), 100);
    scrapeMock.mockResolvedValue([
      { exDate: at(2025, 5, 19), paymentDate: at(2025, 5, 21), dividendPerShare: 1, currency: 'EUR', dividendType: 'ordinary' },
    ]);

    const response = await scrape();
    const body = await response.json();

    expect(body.created).toBe(1);
    const stored = fake.get(`dividends/${body.createdIds[0]}`)!;
    expect(stored.quantity).toBe(100);
    expect(stored.grossAmount).toBe(100);
    expect(stored.taxAmount).toBe(26);
    expect(stored.netAmount).toBe(74);
  });

  it('DQ4: nothing held at the ex-date = no record, not counted as «below the floor»', async () => {
    seedBuy('t1', at(2024, 3, 1), 100);
    fake.set('assetTransactions/t2', {
      userId: 'owner-1', assetId: 'asset-1', type: 'sell', date: ts(at(2026, 5, 15)), quantity: 100,
      pricePerUnit: 10, priceEur: 10, createdAt: ts(at(2026, 5, 15)), updatedAt: ts(at(2026, 5, 15)),
    });
    scrapeMock.mockResolvedValue([
      { exDate: at(2026, 5, 18), paymentDate: at(2026, 5, 20), dividendPerShare: 1, currency: 'EUR', dividendType: 'ordinary' },
    ]);

    const body = await (await scrape()).json();

    expect(body.created).toBe(0);
    expect(body.notEntitled).toBe(1);
    expect(body.filtered).toBe(0);
  });

  it('MM1: two paid records at 200 units are listed and nothing is rewritten', async () => {
    seedBuy('t1', at(2024, 3, 1), 100);
    seedBuy('t2', at(2026, 10, 5), 100);
    for (const [id, ex] of [['d1', at(2025, 5, 19)], ['d2', at(2026, 5, 18)]] as const) {
      fake.set(`dividends/${id}`, {
        userId: 'owner-1', assetId: 'asset-1', assetTicker: 'FENI', assetName: 'Fenicottero',
        exDate: ts(ex), paymentDate: ts(ex), quantity: 200, dividendPerShare: 1, grossAmount: 200,
        taxAmount: 52, netAmount: 148, currency: 'EUR', dividendType: 'ordinary', isAutoGenerated: true,
        expenseId: `e-${id}`, createdAt: ts(ex), updatedAt: ts(ex),
      });
    }
    scrapeMock.mockResolvedValue([
      { exDate: at(2025, 5, 19), paymentDate: at(2025, 5, 21), dividendPerShare: 1, currency: 'EUR', dividendType: 'ordinary' },
    ]);

    const body = await (await scrape()).json();

    expect(body.mismatches).toHaveLength(2);
    expect(body.mismatches[0]).toMatchObject({ recordedQuantity: 200, entitledQuantity: 100 });
    expect(fake.get('dividends/d1')?.quantity).toBe(200);
    expect(fake.get('dividends/d2')?.quantity).toBe(200);
  });
});
