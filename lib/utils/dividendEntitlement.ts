/**
 * Which quantity is entitled to a dividend or coupon, and what is withheld (pure, tested).
 *
 * The ONE source of the rules in doc/dividendi-quantita/README.md (RQ1–RQ6, RQ12, RT1–RT2): the
 * scrape route, the three cron phases, the ledger hook and the mismatch list all read it.
 *
 * ZERO Firebase imports, TIME IS INJECTED (`now`).
 */

import type { Asset } from '@/types/assets';
import type { AssetTransaction } from '@/types/assetTransactions';
import type { Dividend } from '@/types/dividend';
import { getItalyDateIso } from '@/lib/utils/dateHelpers';
import {
  EPSILON,
  LedgerValidationError,
  replayTransactions,
  sortTransactionsForReplay,
} from '@/lib/utils/assetTransactionUtils';

/** Default withholding rate (percent) when the instrument carries none. */
export const DEFAULT_DIVIDEND_TAX_RATE = 26;

/**
 * Quantity entitled to the payment whose reference date is `referenceDate` (ex-date for dividends,
 * payment date for coupons and the final premium).
 *
 * RQ1: the position at the close of the Italian calendar day BEFORE the reference day (a buy on
 * the day itself does not count, a sell on the day itself does not remove the right).
 * RQ6: a reference day after today is a forecast, «if nothing changes»: today's quantity.
 * RQ3: when the ledger cannot say — no operations: `asset.quantity`; empty prefix: the baseline's
 * quantity if the first operation is the baseline, else 0; an invalid prefix: `asset.quantity`.
 */
export function entitledQuantity(input: {
  asset: Pick<Asset, 'quantity'>;
  transactions: AssetTransaction[];
  referenceDate: Date;
  now: Date;
}): number {
  const { asset, transactions, referenceDate, now } = input;
  if (transactions.length === 0) return asset.quantity;

  const referenceDay = getItalyDateIso(referenceDate);
  if (referenceDay > getItalyDateIso(now)) return asset.quantity;

  const sorted = sortTransactionsForReplay(transactions);
  const prefix = sorted.filter((t) => getItalyDateIso(t.date) < referenceDay);
  if (prefix.length === 0) {
    const first = sorted[0];
    return first.isBaseline === true ? first.quantity : 0;
  }
  try {
    return replayTransactions(prefix).quantity;
  } catch (error) {
    if (error instanceof LedgerValidationError) {
      console.error('[entitledQuantity] invalid ledger prefix, using the asset quantity:', error.userMessage);
      return asset.quantity;
    }
    throw error;
  }
}

/** True when the quantity pays nothing (RQ4). */
export function isZeroQuantity(quantity: number): boolean {
  return quantity <= EPSILON;
}

/** RT1: the instrument's rate; a written 0 is a value. */
export function resolveDividendTaxRate(asset: Pick<Asset, 'taxRate'>): number {
  return asset.taxRate ?? DEFAULT_DIVIDEND_TAX_RATE;
}

/** RT2: withholding and net of a gross amount at the instrument's rate. */
export function resolveDividendWithholding(
  grossAmount: number,
  asset: Pick<Asset, 'taxRate'>,
): { taxAmount: number; netAmount: number } {
  const taxAmount = (grossAmount * resolveDividendTaxRate(asset)) / 100;
  return { taxAmount, netAmount: grossAmount - taxAmount };
}

/** Amounts of a payment of `dividendPerShare` on `quantity` units (RQ5). */
export function computeDividendAmounts(
  dividendPerShare: number,
  quantity: number,
  asset: Pick<Asset, 'taxRate'>,
): { grossAmount: number; taxAmount: number; netAmount: number } {
  const grossAmount = dividendPerShare * quantity;
  return { grossAmount, ...resolveDividendWithholding(grossAmount, asset) };
}

type PaymentFlags = Pick<Dividend, 'isAutoGenerated' | 'expenseId' | 'manuallyEdited' | 'paymentDate'>;

/**
 * Open payment: generated by the app, not yet entered in the cashflow, not corrected by hand, and
 * paid today or later (Italian day). Open payments follow the ledger.
 */
export function isOpenPayment(dividend: PaymentFlags, now: Date): boolean {
  return (
    dividend.isAutoGenerated &&
    !dividend.expenseId &&
    dividend.manuallyEdited !== true &&
    getItalyDateIso(dividend.paymentDate) >= getItalyDateIso(now)
  );
}

/** The date an entitled quantity is read at: coupons and the final premium pay on `paymentDate`. */
export function dividendReferenceDate(
  dividend: Pick<Dividend, 'dividendType' | 'exDate' | 'paymentDate'>,
): Date {
  return dividend.dividendType === 'coupon' || dividend.dividendType === 'finalPremium'
    ? dividend.paymentDate
    : dividend.exDate;
}

export interface QuantityMismatch {
  dividendId: string;
  exDate: Date;
  paymentDate: Date;
  dividendType: Dividend['dividendType'];
  recordedQuantity: number;
  entitledQuantity: number;
}

/**
 * RQ12: closed, app-generated, not hand-corrected payments whose quantity differs from the
 * ledger's by more than EPSILON. Read-only: nothing is rewritten (D-DV4).
 */
export function findQuantityMismatches(
  dividends: Dividend[],
  transactions: AssetTransaction[],
  asset: Pick<Asset, 'quantity'>,
  now: Date,
): QuantityMismatch[] {
  const result: QuantityMismatch[] = [];
  for (const dividend of dividends) {
    if (!dividend.isAutoGenerated || dividend.manuallyEdited === true) continue;
    if (isOpenPayment(dividend, now)) continue;
    const entitled = entitledQuantity({
      asset,
      transactions,
      referenceDate: dividendReferenceDate(dividend),
      now,
    });
    if (Math.abs(dividend.quantity - entitled) > EPSILON) {
      result.push({
        dividendId: dividend.id,
        exDate: dividend.exDate,
        paymentDate: dividend.paymentDate,
        dividendType: dividend.dividendType,
        recordedQuantity: dividend.quantity,
        entitledQuantity: entitled,
      });
    }
  }
  return result;
}
