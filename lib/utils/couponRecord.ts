/**
 * The dividend record of a bond's next coupon or final premium (pure, tested).
 *
 * ONE builder for the cron's phase 3 and the ledger hook, so the two cannot diverge
 * (doc/dividendi-quantita RQ7). The client scheduler posts the same fields and the server
 * recomputes quantity and amounts from the instrument (RQ11).
 */

import type { Asset, BondDetails } from '@/types/assets';
import type { DividendFormData } from '@/types/dividend';
import { buildCouponNote, resolveCoupon } from '@/lib/utils/couponUtils';
import { computeDividendAmounts } from '@/lib/utils/dividendEntitlement';
import { stripFloatNoise } from '@/lib/utils/floatNoise';

type CouponAsset = Pick<Asset, 'currency' | 'taxRate' | 'averageCost'>;

/** The coupon paid on `paymentDate` on `quantity` units. */
export function buildCouponDividendData(input: {
  assetId: string;
  asset: CouponAsset;
  bondDetails: BondDetails;
  paymentDate: Date;
  quantity: number;
}): DividendFormData {
  const { assetId, asset, bondDetails, paymentDate, quantity } = input;
  const resolved = resolveCoupon(paymentDate, bondDetails, bondDetails.nominalValue ?? 1);
  return {
    assetId,
    exDate: paymentDate,
    paymentDate,
    dividendPerShare: resolved.perShare,
    quantity,
    ...computeDividendAmounts(resolved.perShare, quantity, asset),
    currency: asset.currency,
    dividendType: 'coupon',
    isAutoGenerated: true,
    isProvisional: resolved.isProvisional,
    notes: buildCouponNote(resolved, bondDetails.couponFrequency),
    costPerShare: asset.averageCost,
  };
}

/** The final loyalty premium paid at maturity on `quantity` units. */
export function buildFinalPremiumDividendData(input: {
  assetId: string;
  asset: CouponAsset;
  bondDetails: BondDetails;
  maturityDate: Date;
  quantity: number;
}): DividendFormData | null {
  const { assetId, asset, bondDetails, maturityDate, quantity } = input;
  if (!bondDetails.finalPremiumRate) return null;
  const perShare = stripFloatNoise((bondDetails.finalPremiumRate / 100) * (bondDetails.nominalValue ?? 1));
  return {
    assetId,
    exDate: maturityDate,
    paymentDate: maturityDate,
    dividendPerShare: perShare,
    quantity,
    ...computeDividendAmounts(perShare, quantity, asset),
    currency: asset.currency,
    dividendType: 'finalPremium',
    isAutoGenerated: true,
    notes: `Premio finale a scadenza — ${bondDetails.finalPremiumRate}%`,
    costPerShare: asset.averageCost,
  };
}
